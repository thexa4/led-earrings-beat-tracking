#!/usr/bin/env python3
"""Generate noisePalettes.go: the five ledsgo Palette16 palettes used by the
noise() animation, re-encoded as compile-time constant strings (16 entries x
RGBA). Same reason as flags.go: a `var noisePatterns` containing [16]color.RGBA
arrays costs a runtime initializer (~330 B of code), the same bytes again as
a .data flash image, and 1,280 B of RAM for state that is never written.
As const strings they are flash-only and need no init code.

The palette data is read from the ledsgo module source so the colors cannot
drift from the library.
"""
import re, sys

LEDSGO = "/home/max/go/pkg/mod/github.com/aykevl/ledsgo@v0.0.0-20260626151027-da87c061fab6"

# namedcolors.go: Name = color.RGBA{r, g, b, a}
colors = {}
src = open(f"{LEDSGO}/namedcolors.go").read()
for m in re.finditer(r'(\w+)\s*=\s*color\.RGBA\{([^}]*)\}', src):
    name, args = m.group(1), m.group(2)
    vals = [int(x, 0) for x in args.split(',')]
    colors[name] = tuple(vals)

# palette.go: Name = Palette16{ C1, C2, ... }
pal_src = open(f"{LEDSGO}/palette.go").read()
palettes = {}
for m in re.finditer(r'(\w+)\s*=\s*Palette16\{(.*?)\n\t\}', pal_src, re.S):
    name, body = m.group(1), m.group(2)
    body = re.sub(r'//[^\n]*', '', m.group(2))
    # Tokenize respecting braces: entries are either identifiers or inline
    # color.RGBA{r, g, b, a} literals (RainbowColors uses those).
    names = re.findall(r'color\.RGBA\{[^}]*\}|\w+', body)
    rgba = []
    for n in names:
        m2 = re.match(r'color\.RGBA\{(.*)\}$', n)
        if m2:
            vals = tuple(int(x, 0) for x in m2.group(1).split(','))
            rgba.append(vals)
            continue
        if n not in colors:
            sys.exit(f"{name}: unknown color {n}")
        rgba.append(colors[n])
    # Go pads a short array literal with zero values, so ledsgo's own 15-entry
    # palettes are valid there; reproduce that padding.
    rgba += [(0, 0, 0, 0)] * (16 - len(rgba))
    palettes[name] = rgba

used = ["PartyColors", "RainbowColors", "ForestColors", "OceanColors", "CloudColors"]
for n in used:
    if n not in palettes:
        sys.exit(f"missing palette {n}")

def esc(bs):
    # Always \xHH, uppercase: the payload is color data, never text, and raw
    # printable bytes between the escapes read as noise.
    return ''.join(f'\\x{v:02X}' for v in bs)

lines = ['package main\n', '''
// The five noise() palettes (from ledsgo, which gets them from FastLED's
// colorpalettes.cpp), stored as constant strings: 16 RGB entries, three bytes
// each (alpha dropped - nothing reads it, see flags.go). See gen_flags.py /
// flags.go for the same trick and why: the ledsgo Palette16 values as plain
// vars would need ~1.3 kB of RAM for read-only data, the same bytes again as
// a .data image, and ~330 B of init code to copy them.
//
// Generated by gen_palettes.py from the ledsgo module source; regenerate
// rather than editing by hand. Every byte is an explicit \\xHH escape.

// palette16At returns the palette color at a 16-bit position, interpolating
// between neighbours and wrapping at the top. Bit-identical to
// ledsgo.Palette16.ColorAt. Inlined into noise, where a call per LED would
// cost brightness; the ported patterns share it through paletteAt.
func palette16At(p string, position uint16) Color {
	index := int(position >> 12)
	next := (index + 1) & 15
	i, j := index*3, next*3
	alpha := uint8(position >> 4)
	return NewColor(
		blend8(p[i], p[j], alpha),
		blend8(p[i+1], p[j+1], alpha),
		blend8(p[i+2], p[j+2], alpha))
}

const (
''']
for name in used:
    bs = []
    for (r, g, b, a) in palettes[name]:
        bs += [r, g, b]  # alpha is not stored: nothing reads it
    lines.append(f'\t{name:<{max(map(len, used))}} = "{esc(bs)}"\n')
lines.append(')\n')

open('noisePalettes.go', 'w').write(''.join(lines))
print('noisePalettes.go written:', ', '.join(used))
