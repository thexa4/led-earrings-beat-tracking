#!/usr/bin/env python3
"""What the two earrings' hash sees, band by band, during the tone fixture.

Reads the live syncPipe over SWD while /tmp/psync/tones.wav loops:

  smooth[b]   log2 band energy (Q8) after smoothing and the relative floor -
              the exact array the shape and hot bits are derived from
  agcPeak     input peak-to-peak in raw ADC counts the AGC is tracking
  agcShift    applied gain in bits
  total       sum of band energies (Q8) - overall loudness in the hash domain

Quantities come from `smooth`, not from the raw band accumulators: those
(`filters.energy`) are reset every frame, so an asynchronous read catches a
partial frame and shows up to 20 dB of pure read-phase noise. `smooth` changes
only at a frame boundary and has the AGC step folded in, which is also what
makes it comparable between two devices sitting at different gains.

Two things are reported, because they answer different questions:

  burst minus gap, per band   - is there signal at all, and is it in the band the
                                tone falls in? (capture health)
  shape = smooth - mean(smooth), and L minus R of that - the gain-invariant
                                tilt the shape bits encode, which is the
                                disagreement that shows up as different colours.

Ladder cutoffs from BankK (fc = -ln(1 - k/2^14) * fs / 2pi, fs = 16 kHz):
250, 397, 630, 1000, 1585, 2521, 4002 Hz, so band b is the gap below pole b.

Field offsets come from syncdsp/layout.json, generated by the Go compiler; see
tools/level.py for why hardcoding them went wrong once already.

Usage: tools/hashview.py [--cycles 3] [--elf firmware.elf]
"""

import argparse
import json
import os
import subprocess
import sys
import time

import numpy as np

sys.path.insert(0, __file__.rsplit("/", 1)[0])
import telem  # noqa: E402

LAYOUT = os.path.join(os.path.dirname(__file__), "..", "syncdsp", "layout.json")

CYCLE = 16.0  # tones.wav: 1 s lead, then (2 s burst + 1 s gap) x 5
TONES = [150, 400, 1000, 2500, 5000]
# Two samples mid-burst per tone, four in the gaps.
BURST = ([(1 + k * 3 + 0.6, k) for k in range(5)] +
         [(1 + k * 3 + 1.4, k) for k in range(5)])
GAP = [(1 + k * 3 + 2.6, None) for k in range(4)]
PHASES = sorted(BURST + GAP)

BANDS = ["<250", "250-400", "400-630", "630-1k", "1-1.6k", "1.6-2.5k",
         "2.5-4k", ">4k"]
# Band each tone should dominate in a one-pole ladder (not merely the first
# pole above it).
EXPECT = [0, 2, 3, 5, 7]

AGC_LOW, AGC_HIGH, AGC_MAX = 3000, 12000, 6


def load_layout(path):
    """Field offsets from syncdsp/layout.json.

    Regenerate with WRITE_LAYOUT=1 go test ./syncdsp/ -run TestExportLayout. A
    stale file silently reads a plausible number from the wrong address, so
    refuse to run rather than report fiction.
    """
    with open(path) as f:
        lay = json.load(f)
    src = os.path.join(os.path.dirname(path), "pipeline.go")
    if os.path.getmtime(src) > os.path.getmtime(path):
        raise SystemExit(f"{path} is older than pipeline.go; regenerate:\n"
                         f"  WRITE_LAYOUT=1 go test ./syncdsp/ -run TestExportLayout")
    return lay


def sig(v):
    return v - (1 << 32) if v >= (1 << 31) else v


def q8db(v):
    """log2-magnitude Q8 to dB."""
    return np.asarray(v, dtype=float) / 256 * 6.0206


class Dev:
    """One earring, read through its OpenOCD telnet port."""

    def __init__(self, name, port, pipe, lay):
        self.name = name
        self.ocd = telem.OpenOCD("localhost", port)
        # One contiguous read covering the lowest .. highest exported field.
        self.base = min(f["offset"] for f in lay.values())
        end = max(f["offset"] + 4 * f["words"] for f in lay.values())
        self.nwords = (end - self.base) // 4
        self.addr = pipe + self.base
        self.ix = {k: (f["offset"] - self.base) // 4 for k, f in lay.items()}
        self.n = {k: lay[k]["words"] for k in lay}

    def read(self):
        b = self.ocd.mdw(self.addr, self.nwords)

        def get(k):
            o = self.ix[k]
            return np.array([sig(x) for x in b[o:o + self.n[k]]], dtype=float)

        one = lambda k: get(k)[0]  # noqa: E731
        return {"smooth": get("smooth"), "agcPeak": one("agcPeak"),
                "agcShift": one("agcShift"), "total": one("total"),
                "level": one("level"), "onsetAge": one("onsetAge")}

    def close(self):
        self.ocd.close()


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--elf", default="firmware.elf")
    ap.add_argument("--cycles", type=int, default=3)
    ap.add_argument("--ports", default="4445,4446")
    ap.add_argument("--names", default="L,R")
    a = ap.parse_args()

    lay = load_layout(LAYOUT)["fields"]
    s = telem.resolve_symbols(a.elf)
    pipe = s[next(k for k in s if k.endswith("main.syncPipe"))]
    names = a.names.split(",")
    ports = [int(p) for p in a.ports.split(",")]
    devs = [Dev(n, p, pipe, lay) for n, p in zip(names, ports)]
    print(f"syncPipe = 0x{pipe:08x}  devices {'/'.join(names)} on {a.ports}")

    player = subprocess.Popen(["ffplay", "-v", "error", "-nodisp", "-autoexit",
                               "-loop", "40", "/tmp/psync/tones.wav"])
    time.sleep(0.5)
    t0 = time.time()

    burst = {d.name: {i: [] for i in range(5)} for d in devs}
    gaps = {d.name: [] for d in devs}
    agc = {d.name: [] for d in devs}
    try:
        for c in range(a.cycles):
            for ph, i in PHASES:
                target = t0 + (c + 1) * CYCLE + ph
                while time.time() < target:
                    time.sleep(0.01)
                for d in devs:
                    r = d.read()
                    agc[d.name].append((r["agcPeak"], r["agcShift"]))
                    (gaps[d.name] if i is None else burst[d.name][i]).append(r)
    finally:
        player.kill()
        player.wait()
        for d in devs:
            d.close()

    if not all(gaps[d.name] for d in devs):
        raise SystemExit("no gap samples: check the fixture timing")

    head = " " * 20 + "".join(f"{l:>10s}" for l in BANDS)
    print("\n=== capture health: smooth during a burst, minus during a gap (dB)")
    print(head)
    for d in devs:
        g = np.median([r["smooth"] for r in gaps[d.name]], axis=0)
        for i in range(5):
            e = np.median([r["smooth"] for r in burst[d.name][i]], axis=0)
            delta = q8db(e - g)
            best = int(np.argmax(delta))
            note = "ok" if best == EXPECT[i] else f"peak in band {best}"
            print(f"{d.name + ' ' + str(TONES[i]) + ' Hz':20s}" +
                  "".join(f"{v:10.1f}" for v in delta) + f"   {note}")
        pk = np.median([p for p, _ in agc[d.name]])
        sh = np.median([x for _, x in agc[d.name]])
        post = pk * 2 ** sh
        state = ("PINNED AT MAX GAIN AND STILL LOW"
                 if sh >= AGC_MAX and post < AGC_LOW
                 else "below band" if post < AGC_LOW
                 else "above band" if post > AGC_HIGH else "in band")
        print(f"{d.name + ' agcPeak':20s}{pk:10.0f} counts p-p, gain 2^{sh:.0f}"
              f" -> {post:.0f}  {state}  (band {AGC_LOW}-{AGC_HIGH}, cap 2^{AGC_MAX})")

    if len(devs) != 2:
        return
    print("\n=== hash view: spectral SHAPE (smooth minus its own band mean, dB).")
    print("    Two devices that show the same colour have rows that match.")
    print(head)
    for idx in range(5):
        rows = {}
        for d in devs:
            v = np.median([r["smooth"] for r in burst[d.name][idx]], axis=0)
            rows[d.name] = q8db(v - v.mean())  # Q8 difference -> dB
        for d in devs:
            print(f"{d.name + ' ' + str(TONES[idx]):20s}" +
                  "".join(f"{v:10.1f}" for v in rows[d.name]))
        diff = rows[names[0]] - rows[names[1]]
        print(f"{names[0] + ' - ' + names[1]:20s}" +
              "".join(f"{v:10.1f}" for v in diff) +
              f"   max {np.abs(diff).max():.1f} dB")
    v = np.median([r["smooth"] for r in gaps[names[0]]], axis=0)
    w = np.median([r["smooth"] for r in gaps[names[1]]], axis=0)
    diff = q8db((v - v.mean()) - (w - w.mean()))
    print(f"{'silence':20s}" + "".join(f"{x:10.1f}" for x in diff) +
          f"   max {np.abs(diff).max():.1f} dB")


if __name__ == "__main__":
    main()
